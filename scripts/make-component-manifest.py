#!/usr/bin/env python3
"""Pins what a slim build downloads: one sha256 per file, read from the staged models.

    make-component-manifest.py [--models <dir>]            rewrite the Swift manifest
    make-component-manifest.py [--models <dir>] --check    exit 1 if it would change
    make-component-manifest.py --check-remote              exit 1 unless Hugging Face,
                                                           at the pinned revisions, serves
                                                           exactly these bytes (network)

The on-demand components (docs/SLIM-DOWNLOAD.md) are downloaded by the app from
Hugging Face at a pinned commit and refused unless every file hashes to what is
written in Sources/MoeComponents/ComponentManifest.swift. This writes that file
from the staged `Models/` — the very bytes a full build ships — so "what the app
would fetch" and "what the app used to carry" cannot drift apart unnoticed.
`build.sh` runs `--check` whenever MOE_ON_DEMAND_COMPONENTS is not `off`.

Which folders: the ON_DEMAND_MODELS line of scripts/fetch-models.sh, the one list.
Which revision of which repository: PINS below, checked by --check-remote.
"""
import hashlib
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "Sources/MoeComponents/ComponentManifest.swift"
LISTS = ROOT / "scripts/fetch-models.sh"

# folder (FluidAudio's cache name) -> (Hugging Face repository, pinned commit)
PINS = {
    "parakeet-ctc-110m-coreml": ("FluidInference/parakeet-ctc-110m-coreml",
                                 "accdafd8cf8a2ff1cabe3c11e54416b405d409aa"),
    "speaker-diarization": ("FluidInference/speaker-diarization-coreml",
                            "7eab74f3463c736418d0eb10296261ae581146c9"),
}


def on_demand() -> list[str]:
    m = re.search(r'^ON_DEMAND_MODELS="(.*)"$', LISTS.read_text(), re.M)
    if not m or not m.group(1).split():
        sys.exit(f"✗ no ON_DEMAND_MODELS line in {LISTS} — refusing to guess the list")
    names = m.group(1).split()
    for n in names:
        if n not in PINS:
            sys.exit(f"✗ {n} is on demand but has no pinned repository in {__file__}")
    return names


def sha256(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def render(models: pathlib.Path) -> str:
    out = [
        "// Generated by scripts/make-component-manifest.py from the staged Models/.",
        "// Do not edit by hand: build.sh refuses a slim build when this file and the",
        "// staged models disagree. docs/SLIM-DOWNLOAD.md.",
        "",
        "extension ComponentCatalog {",
        "    /// Hugging Face repository and pinned commit, by cache folder.",
        "    static let pins: [String: (repository: String, revision: String)] = [",
    ]
    names = on_demand()
    for n in names:
        repo, rev = PINS[n]
        out.append(f'        "{n}": ("{repo}", "{rev}"),')
    out += ["    ]", "",
            "    /// Every file of every on-demand component: path, bytes, sha256.",
            "    static let manifest: [String: [ComponentFile]] = ["]
    for n in names:
        d = models / n
        if not d.is_dir():
            sys.exit(f"✗ {d} is not staged — run ./scripts/fetch-models.sh first")
        files = sorted(p for p in d.rglob("*") if p.is_file() and p.name != ".DS_Store")
        if any(p.is_symlink() for p in d.rglob("*")):
            sys.exit(f"✗ {d} contains symlinks — re-run ./scripts/fetch-models.sh")
        if not files:
            sys.exit(f"✗ {d} is empty")
        out.append(f'        "{n}": [')
        for p in files:
            rel = p.relative_to(d).as_posix()
            out.append(f'            ComponentFile("{rel}", {p.stat().st_size}, "{sha256(p)}"),')
        out.append("        ],")
    out += ["    ]", "}", ""]
    return "\n".join(out)


def parse_committed() -> dict[str, list[tuple[str, int, str]]]:
    text = OUT.read_text()
    got: dict[str, list[tuple[str, int, str]]] = {}
    current = None
    in_manifest = False
    for line in text.splitlines():
        if "static let manifest" in line:
            in_manifest = True
            continue
        if not in_manifest:
            continue
        m = re.match(r'\s+"([^"]+)": \[$', line)
        if m:
            current = m.group(1)
            got[current] = []
            continue
        m = re.match(r'\s+ComponentFile\("([^"]+)", (\d+), "([0-9a-f]{64})"\),$', line)
        if m and current:
            got[current].append((m.group(1), int(m.group(2)), m.group(3)))
    return got


def check_remote() -> int:
    """The pinned revision must serve exactly the committed manifest."""
    committed = parse_committed()
    if not committed or not all(committed.values()):
        print(f"✗ no manifest could be read from {OUT}", file=sys.stderr)
        return 1
    bad = 0
    for folder, files in committed.items():
        repo, rev = PINS[folder]
        url = f"https://huggingface.co/api/models/{repo}/tree/{rev}?recursive=1&limit=1000"
        # curl, not urllib: python.org's Python has no CA bundle on a Mac that
        # never ran "Install Certificates", and curl uses the system's.
        got = subprocess.run(["/usr/bin/curl", "-fsS", "-m", "60", url], capture_output=True)
        if got.returncode != 0:
            print(f"✗ could not read {repo}@{rev[:10]} from Hugging Face: "
                  f"{got.stderr.decode(errors='replace').strip()}", file=sys.stderr)
            return 1
        tree = {e["path"]: e for e in json.loads(got.stdout) if e["type"] == "file"}
        for path, size, digest in files:
            e = tree.get(path)
            if e is None:
                print(f"✗ {folder}/{path}: not in {repo}@{rev[:10]}", file=sys.stderr)
                bad += 1
            elif "lfs" in e and (e["lfs"]["oid"] != digest or e["lfs"]["size"] != size):
                print(f"✗ {folder}/{path}: the pinned revision serves different bytes", file=sys.stderr)
                bad += 1
            elif "lfs" not in e and e["size"] != size:
                # A small file is a git blob: the API gives its size and a
                # sha1, not a sha256. Size here; the app checks the sha256.
                print(f"✗ {folder}/{path}: {e['size']} bytes at the pin, {size} in the manifest", file=sys.stderr)
                bad += 1
        print(f"  {folder}: {len(files)} files checked against {repo}@{rev[:10]}")
    return 1 if bad else 0


def main() -> int:
    args = sys.argv[1:]
    if "--check-remote" in args:
        return check_remote()
    models = ROOT / "Models"
    if "--models" in args:
        models = pathlib.Path(args[args.index("--models") + 1])
    text = render(models)
    if "--check" in args:
        if not OUT.is_file() or OUT.read_text() != text:
            print(f"✗ {OUT.relative_to(ROOT)} does not describe the models staged in {models}.",
                  file=sys.stderr)
            print("  A slim build would download bytes that are not the ones this build was",
                  file=sys.stderr)
            print("  tested with. Run scripts/make-component-manifest.py, review the diff, and",
                  file=sys.stderr)
            print("  bump the pinned revision in it if Hugging Face moved.", file=sys.stderr)
            return 1
        print(f"  on-demand manifest: matches {models}")
        return 0
    OUT.write_text(text)
    print(f"✓ wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
